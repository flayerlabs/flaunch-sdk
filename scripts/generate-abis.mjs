#!/usr/bin/env node
// Regenerates src/abi from flaunch-v3-protocol's Foundry artifacts. Build them first:
//   (cd ../flaunch-v3-protocol && git submodule update --init --recursive && forge build)
//   pnpm generate:abis [path/to/flaunch-v3-protocol/out]
import { readFileSync, writeFileSync } from "node:fs";

const out = process.argv[2] ?? "../flaunch-v3-protocol/out";
const contracts = [
  ["Flaunch.sol", "Flaunch"],
  ["FlaunchPool.sol", "FlaunchPoolHook"],
  ["BaseToken.sol", "BaseToken"],
  ["PairTokenWhitelist.sol", "PairTokenWhitelist"],
  ["AtomicLaunchZap.sol", "AtomicLaunchZap"],
  ["LaunchZap.sol", "LaunchZap"],
  ["RecipientFactory.sol", "RecipientFactory"],
  ["FeeEscrow.sol", "FeeEscrow"],
  ["StakingRecipient.sol", "StakingRecipient"],
];

const header = "// Generated by scripts/generate-abis.mjs from the flaunch-v3-protocol Foundry artifact. Do not edit.\n";
for (const [file, name] of contracts) {
  const { abi } = JSON.parse(readFileSync(`${out}/${file}/${name}.json`, "utf8"));
  // Unquoted keys, matching the TypeScript style of the hand-written modules
  const body = JSON.stringify(abi, null, 2).replace(/^(\s*)"([A-Za-z_$][\w$]*)":/gm, "$1$2:");
  writeFileSync(`src/abi/${name}.ts`, `${header}export const ${name}Abi = ${body} as const;\n`);
}
writeFileSync(
  "src/abi/index.ts",
  header + [...contracts.map(([, name]) => name), "uniswap"].map((m) => `export * from "./${m}.js";\n`).join(""),
);
console.log(`wrote ${contracts.length} ABIs to src/abi`);
